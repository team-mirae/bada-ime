"""engine/tests/data/robot/: the typing robot's corpora (engine/tests/robot.rs, docs/robot.md).

Law texts (statutes carry no copyright, or an open licence; see engine/tests/data/robot/SOURCES.md),
downloaded into engine/tools/cache/robot/ (not committed):

  curl -L -o us-title17.htm https://www.govinfo.gov/content/pkg/USCODE-2023-title17/html/USCODE-2023-title17.htm
  curl -L -o uk-hra1998.xml https://www.legislation.gov.uk/ukpga/1998/42/data.xml
  curl -L -o ko-constitution.txt 'https://ko.wikisource.org/w/index.php?title=대한민국헌법_(제10호)&action=raw'
  curl -L -o ko-civil.txt 'https://ko.wikisource.org/w/index.php?title=민법_(대한민국,_제9650호)&action=raw'
  curl -L -o jp-constitution.xml https://laws.e-gov.go.jp/api/1/lawdata/321CONSTITUTION
  curl -L -o jp-civil.xml https://laws.e-gov.go.jp/api/1/lawdata/129AC0000000089

and, from ~/Projects/jis-moonshot/corpora: Tatoeba English and Japanese sentences (CC BY 2.0 FR),
Common Voice Korean sentences (CC0).

Japanese is stored with its reading, one phrase (a content word and the particles and auxiliaries
after it) per line: surface, tab, hiragana. Readings come from SudachiPy with SudachiDict core
(Apache-2.0), in tools/analysis/.venv:

  tools/analysis/.venv/bin/pip install sudachipy sudachidict_core
  tools/analysis/.venv/bin/python engine/tools/build_robot_corpus.py

Each source is sampled evenly (fixed, no randomness) down to SENTENCES sentences.
"""
import bz2, html, os, re, xml.etree.ElementTree as ET

HERE = os.path.dirname(os.path.abspath(__file__))
CACHE = os.path.join(HERE, "cache", "robot")
MOONSHOT = os.path.expanduser("~/Projects/jis-moonshot/corpora")
OUT = os.path.join(HERE, "..", "tests", "data", "robot")
SENTENCES = 400


def sample(lines, n=SENTENCES):
    lines = [l for l in lines if l]
    if len(lines) <= n:
        return lines
    step = len(lines) / n
    return [lines[int(i * step)] for i in range(n)]


def sentences(text, end=r"(?<=[.;:])\s+"):
    out = []
    for para in text.split("\n"):
        para = re.sub(r"\s+", " ", para).strip()
        out += [s.strip() for s in re.split(end, para) if len(s.strip()) > 20]
    return out


def write(name, lines, header):
    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, name), "w", encoding="utf-8") as f:
        f.write(f"# {header} Generated by tools/build_robot_corpus.py.\n")
        for l in lines:
            f.write(l + "\n")
    print(f"{name}: {len(lines)} lines")


# ---------- English ----------

def us_law():
    raw = open(os.path.join(CACHE, "us-title17.htm"), encoding="utf-8").read()
    raw = re.sub(r"(?s)<(script|style)[^>]*>.*?</\1>", "", raw)
    raw = re.sub(r"(?i)<(br|p|div|h\d)[^>]*>", "\n", raw)
    text = html.unescape(re.sub(r"<[^>]+>", " ", raw))
    lines = [s for s in sentences(text) if re.search(r"[a-z]{3}", s) and not s.startswith("(Pub.")]
    return sample(lines)


def uk_law():
    root = ET.parse(os.path.join(CACHE, "uk-hra1998.xml")).getroot()
    paras = []
    for el in root.iter():
        if el.tag.endswith("}Text"):
            paras.append("".join(el.itertext()))
    return sample(sentences("\n".join(paras)))


def tatoeba(lang):
    out = []
    for line in bz2.open(os.path.join(MOONSHOT, f"{lang}_sentences.tsv.bz2"), "rt", encoding="utf-8"):
        parts = line.rstrip("\n").split("\t")
        if len(parts) == 3:
            out.append(parts[2])
    return sample(out)


# ---------- Korean ----------

def wikitext(path):
    t = open(path, encoding="utf-8").read()
    t = re.sub(r"(?s)\{\{.*?\}\}", "", t)
    t = re.sub(r"(?s)<ref.*?</ref>|<[^>]+>", "", t)
    t = re.sub(r"\[\[(?:[^|\]]*\|)?([^\]]*)\]\]", r"\1", t)
    t = re.sub(r"'''?|^[=*:#]+|=+$", "", t, flags=re.M)
    return t


def ko_law():
    text = wikitext(os.path.join(CACHE, "ko-constitution.txt")) + "\n" + wikitext(os.path.join(CACHE, "ko-civil.txt"))
    lines = [s for s in sentences(text, r"(?<=다\.)\s+") if re.search(r"[가-힣]{2}", s)]
    return sample(lines)


def ko_common_voice():
    lines = open(os.path.join(MOONSHOT, "derived", "common-voice-sentences-ko", "ko.txt"), encoding="utf-8").read().split("\n")
    return sample([l.strip() for l in lines if re.search(r"[가-힣]", l)])


# ---------- Japanese ----------

def jp_law():
    out = []
    for name in ("jp-constitution.xml", "jp-civil.xml"):
        root = ET.parse(os.path.join(CACHE, name)).getroot()
        out += ["".join(s.itertext()).strip() for s in root.iter("Sentence")]
    return sample([s for s in out if len(s) > 8])


INDEPENDENT = {"名詞", "代名詞", "動詞", "形容詞", "形状詞", "副詞", "連体詞", "接続詞", "感動詞", "接頭辞"}


def hira(kata):
    return "".join(chr(ord(c) - 0x60) if "ァ" <= c <= "ヶ" else c for c in kata)


def phrases(lines):
    """Sentences → (surface, reading) phrases: a content word and what attaches to it."""
    from sudachipy import Dictionary, SplitMode
    tok = Dictionary(dict="core").tokenizer()
    out = []
    for line in lines:
        cur = None
        for m in tok.tokenize(line, SplitMode.C):
            pos = m.part_of_speech()
            surface, reading = m.surface(), hira(m.reading_form())
            if pos[0] in ("補助記号", "空白") or not re.fullmatch(r"[ぁ-んー]+", reading):
                if cur:
                    out.append(cur)
                cur = None
                continue
            # A new phrase at a content word, unless it's a dependent one (なら in ならない) or a
            # prefix just before it.
            starts = pos[0] in INDEPENDENT and pos[1] != "非自立可能" and not (cur and cur[2] == "接頭辞")
            if cur is None or starts:
                if cur:
                    out.append(cur)
                cur = [surface, reading, pos[0]]
            else:
                cur[0] += surface
                cur[1] += reading
                cur[2] = pos[0]
        if cur:
            out.append(cur)
    return [f"{s}\t{r}" for s, r, _ in out]


if __name__ == "__main__":
    write("en-us-law.txt", us_law(), "17 U.S.C. (Copyright), US Code 2023 (govinfo.gov). Public domain.")
    write("en-uk-law.txt", uk_law(), "Human Rights Act 1998 (legislation.gov.uk). Open Government Licence v3.0.")
    write("en-tatoeba.txt", tatoeba("eng"), "Tatoeba English sentences (tatoeba.org). CC BY 2.0 FR.")
    write("ko-law.txt", ko_law(), "대한민국헌법, 민법 (ko.wikisource.org). 법령: 저작권법 제7조, 보호받지 못하는 저작물.")
    write("ko-common-voice.txt", ko_common_voice(), "Common Voice Korean sentences (Mozilla). CC0 1.0.")
    write("ja-law.tsv", phrases(jp_law()), "日本国憲法, 民法 (e-Gov 法令API). 法令: 著作権法第13条, 権利の目的とならない著作物. Readings: SudachiDict core (Apache-2.0).")
    write("ja-tatoeba.tsv", phrases(tatoeba("jpn")), "Tatoeba Japanese sentences (tatoeba.org). CC BY 2.0 FR. Readings: SudachiDict core (Apache-2.0).")
