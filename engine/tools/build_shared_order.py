#!/usr/bin/env python3
"""Which Hangul shows first where brands share a name (docs/layouts/15-bada-roman.md).

Reads the brand files (engine/data/en-ko/brands/*.tsv) and the curated ranking
(engine/data/en-ko/shared-rank.tsv: key, countries best first, basis), and writes
engine/data/en-ko/shared-order.tsv: for every name whose brands differ in Hangul,
`key<TAB>hangul, hangul, ...`, best first. The order, as the owner set it (2026-11-11):
the most revenue, else the most consumer-facing (both in shared-rank.tsv), else the
shortest Hangul, else the earlier country code. The builds append the file to en-ko.tsv
after a `#! order` line.

Usage: python3 engine/tools/build_shared_order.py
"""
import collections
import pathlib
import re

DATA = pathlib.Path(__file__).resolve().parent.parent / "data" / "en-ko"


def key(name):
    return re.sub(r"[^A-Za-z]", "", name).lower()


def main():
    groups = collections.defaultdict(list)  # key -> [(country, hangul)]
    for f in sorted((DATA / "brands").glob("*.tsv")):
        cc = f.stem
        for line in f.read_text(encoding="utf-8").splitlines():
            if line.startswith("#") or not line.strip():
                continue
            fields = line.split("\t")
            if len(fields) < 2 or not fields[1] or re.search(r"[0-9]", fields[0]):
                continue  # names with digits never match (only letters are looked up)
            if key(fields[0]):
                groups[key(fields[0])].append((cc, fields[1]))

    rank = {}
    for line in (DATA / "shared-rank.tsv").read_text(encoding="utf-8").splitlines():
        if line.startswith("#") or not line.strip():
            continue
        fields = line.split("\t")
        rank[fields[0]] = fields[1].split()

    out = [
        "# Generated by engine/tools/build_shared_order.py from brands/*.tsv and shared-rank.tsv: don't edit.",
        "# Where brands share a name, its Hangul spellings, the one that shows first first:",
        "# key<TAB>hangul, hangul, ...",
    ]
    unknown = []
    for k in sorted(groups):
        entries = groups[k]
        if len({h for _, h in entries}) < 2:
            continue
        ranked = rank.get(k, [])
        unknown += [f"{k}: {cc}" for cc in ranked if cc not in {c for c, _ in entries}]

        def order(e):
            cc, h = e
            r = ranked.index(cc) if cc in ranked else len(ranked)
            return (r, len(h.replace(" ", "")), cc)

        seen = []
        for _, h in sorted(entries, key=order):
            if h not in seen:
                seen.append(h)
        out.append(f"{k}\t{', '.join(seen)}")
    (DATA / "shared-order.tsv").write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"{len(out) - 3} names")
    for u in unknown:
        print("shared-rank.tsv lists a country without that name:", u)


if __name__ == "__main__":
    main()
