"""engine/data/emoji.tsv and engine/data/unicode-names.tsv, for layouts 150 Symbols and 151 Unicode.

Sources (Unicode License v3, engine/data/LICENSE-unicode.txt), downloaded into
engine/tools/cache/unicode/ (not committed):

  curl -LO https://unicode.org/Public/emoji/latest/emoji-test.txt
  curl -LO https://unicode.org/Public/UCD/latest/ucd/UnicodeData.txt
  curl -L -o cldr-annotations-en.json https://raw.githubusercontent.com/unicode-org/cldr-json/main/cldr-json/cldr-annotations-full/annotations/en/annotations.json

emoji.tsv: emoji, its name, its CLDR keywords (separated by `|`), and its five skin-tone forms
(light, medium-light, medium, medium-dark, dark; separated by spaces; empty if it has none), in
emoji-test.txt's order. unicode-names.tsv: code point (hex) and name of every named character
(algorithmically named ranges, controls, surrogates and private use left out).
Usage: python3 build_unicode_data.py
"""
import json, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
CACHE = os.path.join(HERE, "cache", "unicode")
OUT = os.path.join(HERE, "..", "data")
TONES = ["light", "medium-light", "medium", "medium-dark", "dark"]

cldr = json.load(open(os.path.join(CACHE, "cldr-annotations-en.json"), encoding="utf-8"))
cldr = cldr["annotations"]["annotations"]

base = []          # emoji, name
tones = {}         # base name -> {tone: emoji}
version = ""
for line in open(os.path.join(CACHE, "emoji-test.txt"), encoding="utf-8"):
    if line.startswith("# Version:"):
        version = line.split(":", 1)[1].strip()
    m = re.match(r"^[0-9A-F ]+;\s*fully-qualified\s*#\s*(\S+)\s+E[\d.]+\s+(.+)$", line.rstrip("\n"))
    if not m:
        continue
    emoji, name = m.group(1), m.group(2)
    t = re.match(r"^(.*): (light|medium-light|medium|medium-dark|dark) skin tone$", name)
    if t:
        tones.setdefault(t.group(1), {})[t.group(2)] = emoji
        continue
    if "skin tone" in name:      # two-tone combinations (people holding hands …): left out
        continue
    base.append((emoji, name))

with open(os.path.join(OUT, "emoji.tsv"), "w", encoding="utf-8") as f:
    f.write(f"# Emoji {version} (emoji-test.txt) with CLDR English keywords; see LICENSE-unicode.txt. Generated by tools/build_unicode_data.py.\n")
    for emoji, name in base:
        keys = cldr.get(emoji, cldr.get(emoji.replace("️", ""), {})).get("default", [])
        keys = [k for k in keys if k.lower() != name.lower()]
        forms = tones.get(name, {})
        tone_forms = " ".join(forms.get(t, "") for t in TONES) if len(forms) == 5 else ""
        f.write(f"{emoji}\t{name}\t{'|'.join(keys)}\t{tone_forms}\n")

n = 0
with open(os.path.join(OUT, "unicode-names.tsv"), "w", encoding="utf-8") as f:
    f.write("# Unicode character names (UnicodeData.txt); see LICENSE-unicode.txt. Generated by tools/build_unicode_data.py.\n")
    for line in open(os.path.join(CACHE, "UnicodeData.txt"), encoding="utf-8"):
        code, name, category = line.split(";")[:3]
        if name.startswith("<") or category in ("Cc", "Cs", "Co"):
            continue
        f.write(f"{code}\t{name}\n")
        n += 1
print(f"emoji {version}: {len(base)} emoji, {sum(1 for v in tones.values() if len(v) == 5)} with skin tones; {n} named characters")
